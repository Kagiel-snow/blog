'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const Match = require('../../source/js/music-match.js');
const song = (fields = {}) => ({ name: 'Coffee', artist: 'beabadoobee', ...fields });
const cloud = (fields = {}) => ({ provider: 'soundcloud', availability: 'public_full', name: 'Coffee', artist: 'beabadoobee',
  durationMs: 127779, fullDurationMs: 127801, ...fields });

test('matcher exposes the same API in CommonJS and in a browser', () => {
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(require.resolve('../../source/js/music-match.js'), 'utf8'), context);
  assert.deepEqual(Object.keys(context.SiteMusicMatch), Object.keys(Match));
  assert.equal(context.SiteMusicMatch.sameRecording(song(), cloud()), true);
});

test('existing Coffee and time machine originals still match', () => {
  assert.equal(Match.sameRecording(song(), cloud()), true);
  assert.equal(Match.sameRecording(song({ name: 'time machine (ft. aren park)', artist: 'mj apanay/aren park' }),
    cloud({ name: 'Time Machine (feat. Aren Park)', artist: 'MJ Apanay', durationMs: 225979, fullDurationMs: 226006 })), true);
});

test('Unicode, punctuation, whitespace and feat./ft. normalize without dropping words', () => {
  assert.equal(Match.recordingName('Ｃｏｆｆｅｅ！'), 'coffee');
  assert.equal(Match.primaryArtist(' Artist ； Collaborator '), 'Artist');
  assert.equal(Match.sameRecording(song({ name: 'Ｃｏｆｆｅｅ！', artist: 'Bea Badoobee' }), cloud()), true);
  assert.equal(Match.recordingName('Coffee (LIVE)'), 'coffeelive');
  assert.equal(Match.recordingName('Coffee feat. Bob'), Match.recordingName('Coffee ft Bob'));
  assert.notEqual(Match.recordingName('Coffee ft Bob'), Match.recordingName('Coffee ft Alice'));
});

test('inside accepts only its complete trailing catalog artist attribution', () => {
  const inside = song({ name: 'inside', artist: 'Juliana Chahayed/Jackson Lundy' });
  const track = cloud({ name: 'inside - Juliana Chahayed and Jackson Lundy', artist: 'Juliana Chahayed' });
  assert.deepEqual(Match.explainMatch(inside, track), { match: true, reason: 'EXACT_RECORDING_METADATA', attributionRemoved: true });
  assert.equal(Match.sameRecording(inside, { ...track, name: 'inside — Jackson Lundy & Juliana Chahayed' }), true);
  for (const name of ['inside - Juliana Chahayed', 'inside - Jackson Lundy',
    'inside - Juliana Chahayed and Jackson Lundy and Someone Else', 'inside - Juliana Chahayed and Jackson Lundy cover',
    'inside - Juliana Chahayed and Juliana Chahayed']) {
    assert.equal(Match.sameRecording(inside, { ...track, name }), false, name);
  }
});

test('a single artist attribution may be removed but partial or extended names may not', () => {
  assert.equal(Match.sameRecording(song(), cloud({ name: 'Coffee - beabadoobee' })), true);
  for (const name of ['Coffee - bea', 'Coffee - beabadoobee uploads', 'Coffee - beabadoobee and Bob', 'Coffee-beabadoobee']) {
    assert.equal(Match.sameRecording(song(), cloud({ name })), false, name);
  }
  assert.equal(Match.sameRecording(song({ artist: 'Brooks and Dunn' }), cloud({ name: 'Coffee - Brooks and Dunn', artist: 'Brooks and Dunn' })), true);
});

test('artist-name substrings and title attributions cannot promote fan uploaders', () => {
  for (const artist of ['beabadoobee fan', 'Bea', 'beabadoobee/Bob', 'Other artist']) {
    assert.equal(Match.sameRecording(song(), cloud({ name: 'Coffee - beabadoobee', artist })), false, artist);
  }
  assert.equal(Match.sameRecording(song({ name: 'inside', artist: 'Juliana Chahayed/Jackson Lundy' }),
    cloud({ name: 'inside - Juliana Chahayed and Jackson Lundy', artist: 'Jackson Lundy' })), false);
});

test('every added version or collaborator remains significant before or after attribution', () => {
  for (const version of ['cover', 'live', 'remix', 'instrumental', 'sped up', 'slowed', 'version 2', 'feat. Bob']) {
    for (const name of [`Coffee (${version})`, `Coffee ${version} - beabadoobee`, `Coffee - beabadoobee (${version})`]) {
      assert.equal(Match.sameRecording(song(), cloud({ name })), false, name);
    }
  }
  assert.equal(Match.sameRecording(song({ name: 'Coffee (live)' }), cloud({ name: 'Coffee live - beabadoobee' })), true,
    'an explicitly requested live recording can match that same live recording');
});

test('empty, unknown, deleted and autogenerated artist identities never match', () => {
  for (const artist of ['', '未知歌手', '未知作者', '未知用户', '用户已注销', '账号已注销', '帐号已注销', '已注销',
    'Unknown Artist', 'Deleted User', 'SoundCloud User', 'User 123456', 'Anonymous']) {
    assert.equal(Match.sameRecording(song({ artist }), cloud({ artist })), false, artist);
  }
  assert.equal(Match.sameRecording(song({ artist: 'beabadoobee/未知歌手' }), cloud()), false);
  assert.equal(Match.sameRecording(song(), cloud({ artist: 'bea\u200bbadoobee' })), false);
});

test('only public full tracks with complete provider-specific durations can match', () => {
  for (const fields of [{ availability: 'unchecked' }, { availability: undefined }, { provider: 'other' },
    { durationMs: 0 }, { durationMs: NaN }, { durationMs: '127779' }, { durationMs: 30_000 },
    { fullDurationMs: undefined }, { fullDurationMs: 0 }, { fullDurationMs: 130780 }, { durationMs: 86400001, fullDurationMs: 86400001 }]) {
    assert.equal(Match.sameRecording(song(), cloud(fields)), false, JSON.stringify(fields));
  }
  assert.equal(Match.sameRecording(song(), cloud({ durationMs: 124801 })), true, 'inclusive three second encoding tolerance');
  assert.equal(Match.sameRecording(song(), cloud({ provider: 'audius', fullDurationMs: undefined })), true);
  assert.equal(Match.sameRecording(song(), cloud({ provider: 'audius', durationMs: 0 })), false);
});

test('malformed input stays a negative match without throwing or mutating metadata', () => {
  for (const value of [undefined, null, '', 42, [], {}]) assert.equal(Match.sameRecording(value, value), false);
  const source = Object.freeze(song()), candidate = Object.freeze(cloud());
  assert.equal(Match.sameRecording(source, candidate), true);
  assert.equal(Match.sameRecording(song({ name: '' }), candidate), false);
  assert.equal(Match.sameRecording(song({ name: 'x'.repeat(1001) }), candidate), false);
});
